import { buildLevel, buildGraybox, SPLIT_DECK_LAYOUT } from '@space-yz/shared';
import { createAnalyzer, defaultOptions, findSamples } from '../map/metrics';
import { mapConfig } from '../map/maps';
import { measureOpenness, opennessProblems } from '../map/openness';
const t0 = Date.now();
const def = buildGraybox(SPLIT_DECK_LAYOUT);
const an = createAnalyzer(buildLevel(def), mapConfig('split-deck-graybox', def), defaultOptions(true));
findSamples(an);
const r = measureOpenness(an);
console.log(JSON.stringify(r, null, 1), opennessProblems(r), Date.now() - t0, 'ms');
